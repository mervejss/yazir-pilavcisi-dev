-- 005_past_orders.sql (PostgreSQL/Supabase) : Geçmiş siparişler (platform bazlı). Mevcut tablolara dokunmaz.
CREATE TABLE IF NOT EXISTS past_order_batches (
  id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  batch_key     VARCHAR(80)  NOT NULL UNIQUE,
  platform      VARCHAR(30)  NOT NULL,           -- web | google | trendyol | yemeksepeti | migros | getir
  source_file   VARCHAR(300),
  period_start  DATE,
  period_end    DATE,
  imported_at   TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS past_order_items (
  id                   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  platform             VARCHAR(30)  NOT NULL,
  batch_key            VARCHAR(80)  NOT NULL,
  restaurant_id        VARCHAR(20),
  city                 VARCHAR(50),
  district             VARCHAR(50),
  delivery_model       VARCHAR(40),
  payment_method       VARCHAR(50),
  platform_type        VARCHAR(30),               -- TrendyolGo | Trendyol | Galaxy
  order_code           VARCHAR(10),               -- günlük sayaç, benzersiz DEĞİL
  order_no             VARCHAR(30)  NOT NULL,     -- platform sipariş numarası
  ordered_at           TIMESTAMP,
  handed_to_courier_at TIMESTAMP,
  delivered_at         TIMESTAMP,
  product_name         VARCHAR(120),
  status               VARCHAR(40),
  qty                  INTEGER,
  unit_price           DECIMAL(10,2),
  line_total           DECIMAL(10,2)
);
CREATE INDEX IF NOT EXISTS idx_poi_platform_date ON past_order_items(platform, ordered_at);
CREATE INDEX IF NOT EXISTS idx_poi_order_no ON past_order_items(order_no);

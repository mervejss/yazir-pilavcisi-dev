-- 005b_fix_id_identity.sql (PostgreSQL / Supabase)
-- Sadece bu pakete ait 2 tabloyu düzeltir. Mevcut platform_reviews tablosuna DOKUNMAZ.
-- Tekrar çalıştırmak zararsızdır.
DO $$
DECLARE t text;
BEGIN
  FOREACH t IN ARRAY ARRAY['past_order_batches','past_order_items'] LOOP
    IF EXISTS (
      SELECT 1 FROM information_schema.columns
      WHERE table_schema='public' AND table_name=t AND column_name='id' AND is_identity='NO'
        AND data_type IN ('smallint','integer','bigint')
    ) THEN
      EXECUTE format('ALTER TABLE public.%I ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY', t);
    END IF;
  END LOOP;
END $$;
